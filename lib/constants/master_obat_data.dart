  /// Mencari obat di katalog master berdasarkan query nama atau kategori
  static List<MasterObatItem> search(String query) {
    if (query.trim().isEmpty) return all;
    final q = query.trim().toLowerCase();
    return all.where((o) {
      return o.nama.toLowerCase().contains(q) ||
          o.kategori.toLowerCase().contains(q) ||
          o.dosis.toLowerCase().contains(q);
    }).toList();
  }

  /// Menemukan satu obat berdasarkan nama persis atau fuzzy match
  static MasterObatItem? findByName(String name) {
    if (name.trim().isEmpty) return null;
    final clean = name.trim().toLowerCase();
    for (final o in all) {
      if (o.nama.toLowerCase() == clean) return o;
    }
    for (final o in all) {
      if (o.nama.toLowerCase().contains(clean) || clean.contains(o.nama.toLowerCase())) {
        return o;
      }
    }
    return null;
  }
